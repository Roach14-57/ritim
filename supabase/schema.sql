-- Run this file in Supabase SQL Editor to create Ritim's shared community tables.
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  author_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null check (char_length(author_name) between 2 and 28),
  spotify_id text not null,
  item_type text not null check (item_type in ('track', 'album')),
  title text not null check (char_length(title) between 1 and 200),
  artist text not null check (char_length(artist) between 1 and 200),
  image_url text not null default '',
  spotify_url text not null,
  rating smallint not null check (rating between 1 and 10),
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now()
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  review_id bigint not null references public.reviews(id) on delete cascade,
  author_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null check (char_length(author_name) between 2 and 28),
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now()
);

create table if not exists public.review_likes (
  review_id bigint not null references public.reviews(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (review_id, user_id)
);

create index if not exists reviews_created_at_idx on public.reviews (created_at desc);
create index if not exists comments_review_created_at_idx on public.comments (review_id, created_at asc);
create index if not exists review_likes_review_id_idx on public.review_likes (review_id);

alter table public.reviews enable row level security;
alter table public.comments enable row level security;
alter table public.review_likes enable row level security;

grant select on public.reviews, public.comments, public.review_likes to anon, authenticated;
grant insert, delete on public.reviews, public.comments, public.review_likes to authenticated;
grant usage, select on sequence public.reviews_id_seq, public.comments_id_seq to authenticated;

drop policy if exists "Reviews are public" on public.reviews;
create policy "Reviews are public" on public.reviews for select to anon, authenticated using (true);
drop policy if exists "Members can post reviews as themselves" on public.reviews;
create policy "Members can post reviews as themselves" on public.reviews for insert to authenticated
  with check (
    author_id = (select auth.uid()) and
    author_name = coalesce((select auth.jwt() -> 'user_metadata' ->> 'display_name'), split_part((select auth.jwt() ->> 'email'), '@', 1))
  );
drop policy if exists "Members can delete their own reviews" on public.reviews;
create policy "Members can delete their own reviews" on public.reviews for delete to authenticated using (author_id = (select auth.uid()));

drop policy if exists "Comments are public" on public.comments;
create policy "Comments are public" on public.comments for select to anon, authenticated using (true);
drop policy if exists "Members can comment as themselves" on public.comments;
create policy "Members can comment as themselves" on public.comments for insert to authenticated
  with check (
    author_id = (select auth.uid()) and
    author_name = coalesce((select auth.jwt() -> 'user_metadata' ->> 'display_name'), split_part((select auth.jwt() ->> 'email'), '@', 1))
  );
drop policy if exists "Members can delete their own comments" on public.comments;
create policy "Members can delete their own comments" on public.comments for delete to authenticated using (author_id = (select auth.uid()));

drop policy if exists "Like totals are public" on public.review_likes;
create policy "Like totals are public" on public.review_likes for select to anon, authenticated using (true);
drop policy if exists "Members can like as themselves" on public.review_likes;
create policy "Members can like as themselves" on public.review_likes for insert to authenticated with check (user_id = (select auth.uid()));
drop policy if exists "Members can remove their own likes" on public.review_likes;
create policy "Members can remove their own likes" on public.review_likes for delete to authenticated using (user_id = (select auth.uid()));
